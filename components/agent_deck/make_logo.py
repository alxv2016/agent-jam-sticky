#!/usr/bin/env python3
"""Regenerates logo.c: the startup screen's Agent Jam logo, from agent_jam_logo.png (155 x 35, RGBA) at twice its size — each source pixel
a 2 x 2 block, the alpha thresholded at half — packed as LVGL's LV_COLOR_FORMAT_A1 (one bit a pixel, the most significant bit first), so
the logo draws solid on the glass in whatever colour the screen recolours it (a 310 x 70 image of one bit a pixel is 1.4 KB).

    python3 make_logo.py            # reads agent_jam_logo.png beside it, writes logo.c beside it

Python's standard library only.
"""
import struct
import zlib
from pathlib import Path

SCALE = 2  # the logo at twice its art's size: 310 x 70, the width the screen's column holds with room round it
HERE = Path(__file__).parent


def read_alpha(path):
    """The alpha channel of an 8-bit RGBA PNG: (width, height, one bytes row per pixel row)."""
    data = Path(path).read_bytes()
    i, idat = 8, bytearray()
    while i < len(data):
        n = struct.unpack(">I", data[i:i + 4])[0]
        tag, body = data[i + 4:i + 8], data[i + 8:i + 8 + n]
        i += 12 + n
        if tag == b"IHDR":
            w, h, depth, kind = struct.unpack(">IIBB", body[:10])
            assert depth == 8 and kind == 6, "8-bit RGBA only"
        elif tag == b"IDAT":
            idat += body
    raw, stride, bpp = zlib.decompress(bytes(idat)), w * 4, 4
    rows, prev, at = [], bytearray(stride), 0
    for _ in range(h):
        f, line = raw[at], bytearray(raw[at + 1:at + 1 + stride])
        at += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(bytes(line[3::4]))
        prev = line
    return w, h, rows


def main():
    w, h, rows = read_alpha(HERE / "agent_jam_logo.png")
    w2, h2 = w * SCALE, h * SCALE
    stride = (w2 + 7) // 8
    data = bytearray()
    for y in range(h2):
        for b in range(stride):
            byte = 0
            for k in range(8):
                x = b * 8 + k
                byte |= (1 if x < w2 and rows[y // SCALE][x // SCALE] >= 128 else 0) << (7 - k)
            data.append(byte)
    text = ["// Generated by make_logo.py from agent_jam_logo.png — see that script. Do not edit by hand.",
            "// LV_COLOR_FORMAT_A1: one bit a pixel, most significant first.", "", '#include "lvgl.h"', "",
            f"// The Agent Jam logo at twice its art's size: {w2} x {h2}, {len(data)} bytes.",
            "static const uint8_t logo_map[] = {"]
    for i in range(0, len(data), 16):
        text.append("    " + ", ".join(f"0x{v:02X}" for v in data[i:i + 16]) + ",")
    text += ["};", "extern const lv_image_dsc_t agent_deck_logo;", "const lv_image_dsc_t agent_deck_logo = {",
             f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A1, .flags = 0, .w = {w2}, .h = {h2},",
             f"               .stride = {stride}, .reserved_2 = 0}},", "    .data_size = sizeof(logo_map),", "    .data = logo_map,",
             "    .reserved = NULL,", "    .reserved_2 = NULL,", "};", ""]
    (HERE / "logo.c").write_text("\n".join(text))
    print(f"logo: {w2} x {h2}")


if __name__ == "__main__":
    main()
